<?php

namespace App\Services;

use App\Jobs\SendSmsJob;
use App\Mail\OrderConfirmed;
use App\Mail\PaymentReceived;
use App\Models\Customer;
use App\Models\Order;
use App\Models\OrderItem;
use App\Models\Product;
use App\Models\Transaction;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Carbon;
use Illuminate\Support\Str;

/**
 * Centralised business logic for Order create / cancel / payment workflows.
 * Delegates from OrderController, PosController, SteadfastController
 * so each controller becomes a thin HTTP adapter.
 */
class OrderService
{
    // =============================================
    // CREATE
    // =============================================
    /**
     * Create a new order from a validated request (manual or POS).
     *
     * @param  array  $data  Validated order data (items, totals, customer info…)
     * @param  int    $bizId
     * @param  string $source  'manual' | 'pos' | 'woocommerce' etc.
     * @return Order
     */
    public function create(array $data, int $bizId, string $source = 'manual'): Order
    {
        return DB::transaction(function () use ($data, $bizId, $source) {
            // Back-dated entry: use chosen order_date (keep current clock time on that day) or now()
            $entryDate = !empty($data['order_date'])
                ? Carbon::parse($data['order_date'])->setTimeFrom(now())
                : now();

            // Never price an order from browser-supplied totals — re-price server side.
            $data['items'] = $this->repriceItems($data['items'], $bizId);

            $subtotal = collect($data['items'])->sum('total');
            $discount = (float) ($data['discount'] ?? 0);
            $shipping = (float) ($data['shipping_charge'] ?? $data['shipping_cost'] ?? 0);
            $total    = $subtotal - $discount + $shipping;
            $paid     = (float) ($data['paid_amount'] ?? 0);
            $due      = max(0, $total - $paid);

            $payStatus = 'unpaid';
            if ($paid >= $total) $payStatus = 'paid';
            elseif ($paid > 0)   $payStatus = 'partial';

            $order = Order::create([
                'business_id'       => $bizId,
                'warehouse_id'      => $data['warehouse_id'] ?? null,
                'customer_id'       => $data['customer_id'] ?? null,
                'created_by'        => $data['created_by'] ?? auth()->id(),
                // order_number auto-generated by Order model (PREFIX-YYMM-NNN, source-aware)
                'source'            => $source,
                'status'            => $data['status'] ?? 'pending',
                'payment_status'    => $payStatus,
                'payment_method'    => $data['payment_method'] ?? 'cash',
                'customer_name'     => $data['customer_name'] ?? '',
                'customer_phone'    => $data['customer_phone'] ?? null,
                'shipping_address'  => $data['shipping_address'] ?? null,
                'shipping_area'     => $data['shipping_area'] ?? null,
                'shipping_district' => $data['shipping_district'] ?? null,
                'subtotal'          => $subtotal,
                'discount'          => $discount,
                'shipping_charge'   => $shipping,
                'total'             => $total,
                'paid_amount'       => $paid,
                'due_amount'        => $due,
                'notes'             => $data['notes'] ?? null,
            ]);

            // Persist back-dated timestamp when order_date supplied
            if (!empty($data['order_date'])) {
                $order->created_at = $entryDate;
                $order->save();
            }

            $this->syncItems($order, $data['items'], deductStock: !$order->warehouse_id && $order->holdsStock());
            if ($order->warehouse_id && $order->holdsStock()) {
                app(StockService::class)->deductForOrder($order->load('items'));
            }

            if ($paid > 0) {
                Transaction::create([
                    'business_id'      => $bizId,
                    'created_by'       => $data['created_by'] ?? auth()->id(),
                    'order_id'         => $order->id,
                    'type'             => 'income',
                    'title'            => 'Payment for Order #' . $order->order_number,
                    'amount'           => $paid,
                    'payment_method'   => $order->payment_method,
                    'transaction_date' => $entryDate->toDateString(),
                ]);
            }

            $this->updateCustomerTotals($order, $total, $due);

            return $order;
        });
    }

    // =============================================
    // COLLECT PAYMENT
    // =============================================
    /**
     * Record a partial or full payment against an existing order.
     */
    public function collectPayment(Order $order, float $amount, ?string $date = null): void
    {
        $entryDate = !empty($date) ? Carbon::parse($date) : now();

        $newPaid = min($order->total, $order->paid_amount + $amount);
        $newDue  = max(0, $order->total - $newPaid);
        $payStatus = $newDue <= 0 ? 'paid' : 'partial';

        $order->update([
            'paid_amount'    => $newPaid,
            'due_amount'     => $newDue,
            'payment_status' => $payStatus,
        ]);

        Transaction::create([
            'business_id'      => $order->business_id,
            'created_by'       => auth()->id(),
            'order_id'         => $order->id,
            'type'             => 'income',
            'title'            => 'Payment collected for Order #' . $order->order_number,
            'amount'           => $amount,
            'payment_method'   => $order->payment_method,
            'transaction_date' => $entryDate->toDateString(),
        ]);

        if ($order->customer_id) {
            Customer::where('id', $order->customer_id)->decrement('due_amount', $amount);
        }
    }

    // =============================================
    // COD AUTO-COMPLETE (on delivery)
    // =============================================
    /**
     * When a COD order is marked delivered, auto-mark payment as paid.
     */
    public function completeCod(Order $order): void
    {
        $order->update([
            'paid_amount'    => $order->total,
            'due_amount'     => 0,
            'payment_status' => 'paid',
        ]);

        Transaction::create([
            'business_id'      => $order->business_id,
            'created_by'       => auth()->id(),
            'order_id'         => $order->id,
            'type'             => 'income',
            'title'            => 'COD collected for Order #' . $order->order_number,
            'amount'           => $order->total,
            'payment_method'   => 'cod',
            'transaction_date' => today(),
        ]);
    }

    // =============================================
    // CANCEL / RETURN / REFUND
    // =============================================
    /**
     * Cancel/return an order: restore stock, record refund transaction,
     * update customer due.
     */
    public function cancel(Order $order, string $status = 'cancelled'): void
    {
        if ($order->warehouse_id) {
            app(StockService::class)->restoreForOrder($order->load('items'));
        } else {
            // Historical manual orders were deducted only from the product total.
            foreach ($order->items as $item) {
                if ($item->product_id) Product::where('business_id', $order->business_id)->whereKey($item->product_id)->increment('stock', $item->quantity);
            }
        }

        // Refund transaction if already paid
        if ($order->paid_amount > 0) {
            Transaction::create([
                'business_id'      => $order->business_id,
                'created_by'       => auth()->id(),
                'order_id'         => $order->id,
                'type'             => 'expense',
                'title'            => 'Refund for Order #' . $order->order_number,
                'amount'           => $order->paid_amount,
                'payment_method'   => $order->payment_method,
                'transaction_date' => today(),
            ]);
        }

        // Clear customer due
        if ($order->customer_id && $order->due_amount > 0) {
            Customer::where('id', $order->customer_id)
                ->decrement('due_amount', $order->due_amount);
        }

        $order->update([
            'status'         => $status,
            'paid_amount'    => 0,
            'due_amount'     => 0,
            'payment_status' => 'refunded',
        ]);
    }

    // =============================================
    // SEND SMS NOTIFICATIONS
    // =============================================
    public function notifyConfirmed(Order $order, string $bizName): void
    {
        // SMS
        SendSmsJob::dispatch($order->business_id, 'order_confirmation', [
            'phone'         => $order->customer_phone,
            'customer_name' => $order->customer_name,
            'order_number'  => $order->order_number,
            'total'         => number_format($order->total),
            'business_name' => $bizName,
        ]);

        // Email (if customer has one)
        $this->sendOrderEmail($order, new OrderConfirmed($order));
    }

    public function notifyPaymentReceived(Order $order, float $amount, string $bizName): void
    {
        // SMS
        SendSmsJob::dispatch($order->business_id, 'payment_received', [
            'phone'         => $order->customer_phone,
            'order_number'  => $order->order_number,
            'amount'        => number_format($amount),
            'business_name' => $bizName,
        ]);

        // Email
        $this->sendOrderEmail($order, new PaymentReceived($order, $amount));
    }

    private function sendOrderEmail(Order $order, \Illuminate\Mail\Mailable $mailable): void
    {
        $email = $order->customer?->email;
        if (!$email) return;

        try {
            Mail::to($email)->queue($mailable);
        } catch (\Throwable $e) {
            // Never let email failure break the order flow
            Log::warning('Order email failed: ' . $e->getMessage(), ['order_id' => $order->id]);
        }
    }

    // =============================================
    // HELPERS
    // =============================================
    /**
     * Re-price every line server side.
     *
     * The browser sends price/total, and both are trivially editable, so they are
     * never trusted as-is:
     *   - the line total is ALWAYS recomputed as price x qty - discount (no exceptions),
     *     which alone kills "total does not match price" tampering;
     *   - the unit price is forced to the catalog price for non-privileged users.
     *     owner/admin/manager may still set a custom price, because negotiated
     *     wholesale/exchange pricing is a deliberate feature — those overrides are
     *     logged instead of blocked.
     * Lines without a catalog product (custom/manual lines) keep their price for
     * privileged users and are rejected to 0 for everyone else.
     */
    public function repriceItems(array $items, int $bizId): array
    {
        $mayOverridePrice = (bool) optional(auth()->user())->isManager();

        $catalog = Product::where('business_id', $bizId)
            ->whereIn('id', collect($items)->pluck('product_id')->filter()->unique())
            ->get(['id', 'name', 'price', 'sale_price'])
            ->keyBy('id');

        foreach ($items as $i => $item) {
            $qty      = max(1, (int) ($item['quantity'] ?? 1));
            $lineDisc = max(0, (float) ($item['discount'] ?? 0));
            $sent     = (float) ($item['price'] ?? 0);
            $product  = $catalog->get($item['product_id'] ?? null);

            if ($product) {
                $catalogPrice = (float) ($product->sale_price ?: $product->price);
                $price        = $catalogPrice;

                if (abs($sent - $catalogPrice) > 0.001) {
                    if ($mayOverridePrice) {
                        $price = max(0, $sent);
                        Log::info('Order line price overridden', [
                            'user_id'    => auth()->id(),
                            'product_id' => $product->id,
                            'catalog'    => $catalogPrice,
                            'charged'    => $price,
                        ]);
                    } else {
                        Log::warning('Order line price rejected — catalog price enforced', [
                            'user_id'    => auth()->id(),
                            'product_id' => $product->id,
                            'catalog'    => $catalogPrice,
                            'attempted'  => $sent,
                        ]);
                    }
                }
            } else {
                // Custom (non-catalog) line: only privileged users may name a price.
                $price = $mayOverridePrice ? max(0, $sent) : 0.0;
            }

            $items[$i]['price']    = $price;
            $items[$i]['quantity'] = $qty;
            $items[$i]['discount'] = $lineDisc;
            $items[$i]['total']    = max(0, ($price * $qty) - $lineDisc);
        }

        return $items;
    }

    public function replaceItems(Order $order, array $items, ?int $warehouseId = null): float
    {
        $ids = $order->items->pluck('product_id')->merge(collect($items)->pluck('product_id'))->filter()->unique()->sort();
        Product::where('business_id', $order->business_id)->whereIn('id', $ids)->orderBy('id')->lockForUpdate()->get();
        if ($order->holdsStock()) app(StockService::class)->restoreForOrder($order->load('items'));
        $order->update(['warehouse_id' => $warehouseId ?? $order->warehouse_id]);
        $order->items()->delete();
        $items = $this->repriceItems($items, $order->business_id);
        $this->syncItems($order, $items, deductStock: false);
        if ($order->holdsStock()) app(StockService::class)->deductForOrder($order->load('items'));
        return (float) collect($items)->sum('total');
    }

    private function syncItems(Order $order, array $items, bool $deductStock = true): void
    {
        foreach ($items as $item) {
            // Only accept catalog products that belong to THIS business. A foreign
            // product_id is treated as a custom (non-catalog) line so it can never
            // touch another tenant's stock.
            $product = !empty($item['product_id'])
                ? Product::where('id', $item['product_id'])
                    ->where('business_id', $order->business_id)
                    ->first()
                : null;

            OrderItem::create([
                'order_id'     => $order->id,
                'product_id'   => $product?->id,
                'product_name' => $item['product_name'],
                'price'        => $item['price'],
                'cost_price'   => $item['cost_price'] ?? 0,
                'quantity'     => $item['quantity'],
                'discount'     => $item['discount'] ?? 0,
                'total'        => $item['total'],
            ]);

            if ($deductStock && $product && $product->track_stock) {
                $newStock = max(0, $product->stock - (int) $item['quantity']);
                $product->update(['stock' => $newStock]);
            }
        }
    }

    private function updateCustomerTotals(Order $order, float $total, float $due): void
    {
        if (!$order->customer_id) return;

        Customer::where('id', $order->customer_id)->increment('total_purchase', $total);

        if ($due > 0) {
            Customer::where('id', $order->customer_id)->increment('due_amount', $due);
        }
    }
}
